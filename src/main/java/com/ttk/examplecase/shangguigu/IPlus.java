package com.ttk.examplecase.shangguigu;

public class IPlus {

    public static void main(String[] args) {

        int i = 1;

        System.out.println("i：" + i);
        System.out.println("++i：" + ++i);
        System.out.println("i++：" + i++);
        System.out.println("i：" + i);
        System.out.println("--i：" + --i);
        System.out.println("i--：" + i--);
        System.out.println("i：" + i);

        // 1 2 2 3 2 2 1

    }

}
